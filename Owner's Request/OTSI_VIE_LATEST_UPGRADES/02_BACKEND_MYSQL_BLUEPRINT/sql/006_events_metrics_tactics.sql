CREATE TABLE tactical_windows (
  id                CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  organization_id   CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  video_id          CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  run_id            CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  kind              ENUM('PRESSING','BUILD_UP','TRANSITION','SET_PIECE','DEFENSIVE_BLOCK') NOT NULL,
  team_side         ENUM('HOME','AWAY') NOT NULL,
  from_pts_us       BIGINT UNSIGNED NOT NULL,
  to_pts_us         BIGINT UNSIGNED NOT NULL,
  coverage_ratio    DECIMAL(5,4) NOT NULL,
  metrics           JSON NOT NULL COMMENT 'e.g. PPDA, regains, press height for 05 Pressing Map',
  evidence_state    ENUM('DETECTED','INFERRED','CONFIRMED','NOT_MEASURED') NOT NULL,
  evidence_id       CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  PRIMARY KEY (id),
  KEY ix_tw (organization_id, video_id, kind, team_side, from_pts_us),
  CONSTRAINT fk_tw_video FOREIGN KEY (organization_id, video_id) REFERENCES video_sources(organization_id, id),
  CONSTRAINT fk_tw_run   FOREIGN KEY (organization_id, run_id) REFERENCES pipeline_runs(organization_id, id),
  CONSTRAINT ck_tw_range CHECK (to_pts_us > from_pts_us AND coverage_ratio BETWEEN 0 AND 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci ROW_FORMAT=DYNAMIC;
