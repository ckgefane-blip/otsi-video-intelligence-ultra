"""The OTSI VIE v2 migrator: applies database/migrations/NNNN_*.sql in order, exactly once each, with version tracking.

Rules (ADR-014):
  * `schema_migrations` records version, file name, SHA-256 of the file, who applied it, when, and how long it took.
  * Only PENDING versions run, in ascending order. Re-running is a no-op (repeatable).
  * An APPLIED file whose content changed, a missing/renumbered applied file, or a pending version older than the newest applied one
    STOPS the run with an error. Nothing is dropped or "repaired": a deployed migration is never edited, a fix is a new migration.
  * One run at a time: a named server lock (GET_LOCK) is held for the whole run.
  * MySQL commits DDL implicitly, so a file cannot be rolled back as a unit. A file that fails part-way is NOT recorded; the run stops and
    reports the statement, and the operator restores from the pre-migration snapshot (DEPLOYMENT runbook) — never an automatic retry.

Connection: --dsn mysql://user:password@host:port/database or the env var OTSI_VIE_DB_DSN. The database must already exist.
Usage:  python otsi-vie/tools/db/migrate.py status|up [--dsn ...]
        python otsi-vie/tools/db/migrate.py bootstrap [--dsn sqlite:///...]

DSNs:
  mysql://user:password@host:port/database   (the live/owner server database)
  sqlite:///absolute/path/to/vie.sqlite      (the on-PC local database, ADR-144)

SQLite (safeguard 6): the runner applies database/migrations-sqlite/NNNN_*.sqlite.sql
(the SQLite translation of each MySQL migration, generated by tools/db/sqlite_translate.py)
in order, inside ONE transaction per run, after taking an automatic file backup of the
local database (copy of the .sqlite file + WAL, with a SHA-256 manifest under
<db dir>/.backups/<UTC time>/). If a migration fails, the backup is restored, the
database is left exactly as it was, and the failure is reported in plain words.
A fresh SQLite database is created from database/sqlite-bootstrap.sql (same schema,
all versions recorded as applied). The MySQL path is unchanged, except that setting
OTSI_VIE_PRE_MIGRATION_BACKUP to a command runs it before the MySQL migrations and
aborts if it fails — a server database cannot be file-copied, so its pre-migration
snapshot stays the operator's job (tools/db/backup.py; DEPLOYMENT runbook).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sqlite3
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import unquote, urlparse

try:
    from . import mariadb_compat  # type: ignore[import-not-found]
except ImportError:  # run as a script
    import mariadb_compat  # type: ignore[no-redef]


def _pymysql():
    """pymysql is needed only for the MySQL path; importing it lazily keeps the
    SQLite path (and its tests) working on machines without MySQL client libs."""
    try:
        import pymysql

        return pymysql
    except ImportError:
        raise MigrationError(
            "MySQL support needs the pymysql package installed; "
            "use a sqlite:// DSN for the local database"
        ) from None

MIGRATIONS = Path(__file__).resolve().parents[2] / "database" / "migrations"
SQLITE_MIGRATIONS = Path(__file__).resolve().parents[2] / "database" / "migrations-sqlite"
SQLITE_BOOTSTRAP_FILE = Path(__file__).resolve().parents[2] / "database" / "sqlite-bootstrap.sql"
LOCK = "otsi_vie_migrate"
FILE_RE = re.compile(r"^(\d{4})_[a-z0-9_]+\.sql$")
SQLITE_FILE_RE = re.compile(r"^(\d{4})_[a-z0-9_]+\.sqlite\.sql$")
MS_NOW = "(CAST(unixepoch('subsec')*1000 AS INTEGER))"  # UTC epoch milliseconds, SQLite

BOOTSTRAP = """CREATE TABLE IF NOT EXISTS `schema_migrations` (
  `version` CHAR(4) NOT NULL PRIMARY KEY,
  `name` VARCHAR(191) NOT NULL,
  `sha256` CHAR(64) NOT NULL,
  `applied_by` VARCHAR(191) NOT NULL,
  `applied_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `duration_ms` INT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci"""


class MigrationError(RuntimeError):
    pass


@dataclass(frozen=True)
class Migration:
    version: str
    name: str
    path: Path

    @property
    def sql(self) -> str:
        return self.path.read_text(encoding="utf-8")

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.path.read_bytes()).hexdigest()


def discover(folder: Path = MIGRATIONS) -> list[Migration]:
    found = []
    for p in sorted(folder.glob("*.sql")):
        m = FILE_RE.match(p.name)
        if not m:
            raise MigrationError(f"{p.name}: migration files must be named NNNN_lower_snake.sql")
        found.append(Migration(m.group(1), p.name, p))
    versions = [m.version for m in found]
    if len(set(versions)) != len(versions):
        raise MigrationError(f"duplicate migration versions: {versions}")
    return found


def split_statements(sql: str) -> list[str]:
    """Split a migration file into statements like the mysql client does: honours `DELIMITER x`, quotes, backticks and comments."""
    out, buf, delim = [], [], ";"
    i, n = 0, len(sql)
    line_start = True
    while i < n:
        if line_start:
            m = re.match(r"[ \t]*DELIMITER[ \t]+(\S+)[ \t]*(\r?\n|$)", sql[i:], re.I)
            if m:
                delim = m.group(1)
                i += m.end()
                continue
        c = sql[i]
        if c in ("'", '"', "`"):
            j = i + 1
            while j < n and sql[j] != c:
                j += 2 if sql[j] == "\\" and c != "`" else 1
            buf.append(sql[i:j + 1])
            i = j + 1
            line_start = False
            continue
        if sql.startswith("--", i) or c == "#":
            j = sql.find("\n", i)
            i = n if j < 0 else j
            continue
        if sql.startswith("/*", i):
            j = sql.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        if sql.startswith(delim, i):
            stmt = "".join(buf).strip()
            if stmt:
                out.append(stmt)
            buf = []
            i += len(delim)
            line_start = False
            continue
        buf.append(c)
        line_start = c == "\n"
        i += 1
    tail = "".join(buf).strip()
    if tail:
        out.append(tail)
    return out


def connect(dsn: str):
    u = urlparse(dsn)
    if u.scheme != "mysql" or not u.path.strip("/"):
        raise MigrationError("DSN must look like mysql://user:password@host:port/database")
    pymysql = _pymysql()
    return pymysql.connect(host=u.hostname or "127.0.0.1", port=u.port or 3306, user=unquote(u.username or ""), password=unquote(u.password or ""),
                           database=u.path.strip("/"), charset="utf8mb4", autocommit=True, client_flag=0)


def backend_of(dsn: str) -> str:
    """'mysql' or 'sqlite' for a DSN. Anything else is rejected in plain words."""
    scheme = urlparse(dsn).scheme
    if scheme == "mysql":
        return "mysql"
    if scheme == "sqlite":
        return "sqlite"
    raise MigrationError(f"unsupported DSN scheme {scheme!r}: use mysql://... or sqlite:///...")


def applied(cur) -> dict[str, tuple[str, str]]:
    cur.execute("SELECT version, name, sha256 FROM schema_migrations ORDER BY version")
    return {v: (n, h) for v, n, h in cur.fetchall()}


def plan(cur, migrations: list[Migration]) -> list[Migration]:
    done = applied(cur)
    by_version = {m.version: m for m in migrations}
    for v, (name, digest) in done.items():
        m = by_version.get(v)
        if m is None:
            raise MigrationError(f"applied migration {v} ({name}) is missing from the folder")
        if m.name != name:
            raise MigrationError(f"applied migration {v} was renamed: {name} -> {m.name}")
        if m.sha256 != digest:
            raise MigrationError(f"applied migration {m.name} was edited after it ran (checksum mismatch); write a new migration instead")
    newest = max(done) if done else None
    pending = [m for m in migrations if m.version not in done]
    late = [m.name for m in pending if newest and m.version < newest]
    if late:
        raise MigrationError(f"pending migrations are older than the newest applied one ({newest}): {late}")
    return pending


def up(dsn: str, migrations: list[Migration] | None = None, applied_by: str = "migrate.py") -> list[str]:
    if backend_of(dsn) == "sqlite":
        return up_sqlite(dsn, migrations, applied_by)
    migrations = discover() if migrations is None else migrations
    pymysql = _pymysql()
    conn = connect(dsn)
    ran: list[str] = []
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT GET_LOCK(%s, 30)", (LOCK,))
            if cur.fetchone()[0] != 1:
                raise MigrationError("another migration run holds the lock")
            try:
                # MariaDB (the central server's host, ADR-146 §6): each statement passes through mariadb_compat.rewrite()
                cur.execute("SELECT VERSION()")
                version = str(cur.fetchone()[0])
                maria = mariadb_compat.is_mariadb(version)
                # MariaDB older than 11.4 (this VM's 10.11 test server) has no utf8mb4_0900_ai_ci: the
                # BOOTSTRAP and the migrations name it, so it is rewritten to utf8mb4_unicode_ci there.
                fix_collation = maria and mariadb_compat.collation_needs_rewrite(version)
                cur.execute(mariadb_compat.rewrite_collation(BOOTSTRAP) if fix_collation else BOOTSTRAP)
                pending = plan(cur, migrations)
                if pending:
                    run_pre_migration_backup()
                for m in pending:
                    t0 = time.monotonic()
                    for k, stmt in enumerate(split_statements(m.sql), 1):
                        if maria:
                            stmt = mariadb_compat.rewrite(stmt)
                        if fix_collation:
                            stmt = mariadb_compat.rewrite_collation(stmt)
                        try:
                            cur.execute(stmt)
                        except pymysql.MySQLError as e:
                            raise MigrationError(f"{m.name} statement {k} failed: {e.args}\n{stmt[:400]}") from None
                        cur.execute("SHOW WARNINGS")
                        warnings = [w for w in cur.fetchall() if w[0] != "Note"]
                        if warnings:
                            raise MigrationError(f"{m.name} statement {k} raised warnings: {warnings}")
                    cur.execute("INSERT INTO schema_migrations (version, name, sha256, applied_by, duration_ms) VALUES (%s,%s,%s,%s,%s)",
                                (m.version, m.name, m.sha256, applied_by, int((time.monotonic() - t0) * 1000)))
                    ran.append(m.name)
            finally:
                cur.execute("SELECT RELEASE_LOCK(%s)", (LOCK,))
    finally:
        conn.close()
    return ran


def status(dsn: str) -> list[tuple[str, str, str]]:
    if backend_of(dsn) == "sqlite":
        return status_sqlite(dsn)
    conn = connect(dsn)
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT VERSION()")
            version = str(cur.fetchone()[0])
            fix_collation = mariadb_compat.is_mariadb(version) and mariadb_compat.collation_needs_rewrite(version)
            cur.execute(mariadb_compat.rewrite_collation(BOOTSTRAP) if fix_collation else BOOTSTRAP)
            done = applied(cur)
    finally:
        conn.close()
    return [(m.version, m.name, "applied" if m.version in done else "pending") for m in discover()]


# ------------------------------------------------------------------ #
# SQLite backend (safeguard 6): backup-first, transactional, forward-only
# ------------------------------------------------------------------ #

SQLITE_BOOTSTRAP_TABLE = f"""CREATE TABLE IF NOT EXISTS schema_migrations (
  version TEXT NOT NULL PRIMARY KEY,
  name TEXT NOT NULL,
  sha256 TEXT NOT NULL,
  applied_by TEXT NOT NULL,
  applied_at INTEGER NOT NULL DEFAULT {MS_NOW},
  duration_ms INTEGER NOT NULL
) STRICT"""


def sqlite_path(dsn: str) -> Path:
    """The file path of a sqlite:// DSN. Accepts sqlite:////abs/path,
    sqlite:///abs/path and sqlite:///C:/... (Windows drive letter)."""
    u = urlparse(dsn)
    if u.scheme != "sqlite":
        raise MigrationError("DSN must look like sqlite:///absolute/path/to/vie.sqlite")
    raw = unquote(u.path or "")
    if re.match(r"^/[A-Za-z]:", raw):
        raw = raw[1:]
    p = Path(raw)
    if not p.is_absolute():
        raise MigrationError(f"SQLite DSN must give an absolute file path: {dsn!r}")
    return p


def discover_sqlite(folder: Path = SQLITE_MIGRATIONS) -> list[Migration]:
    found = []
    for p in sorted(folder.glob("*.sqlite.sql")):
        m = SQLITE_FILE_RE.match(p.name)
        if not m:
            raise MigrationError(f"{p.name}: SQLite migrations must be named NNNN_lower_snake.sqlite.sql")
        found.append(Migration(m.group(1), p.name, p))
    versions = [m.version for m in found]
    if len(set(versions)) != len(versions):
        raise MigrationError(f"duplicate SQLite migration versions: {versions}")
    return found


def split_sqlite_statements(sql: str) -> list[str]:
    """Split SQLite SQL into statements the way the sqlite3 shell does:
    accumulate lines until sqlite3.complete_statement() says the buffer is
    a complete statement. This keeps CREATE TRIGGER ... BEGIN ...; ... END;
    intact, which a naive split on ';' would shred."""
    out, buf = [], ""
    for line in sql.splitlines(keepends=True):
        stripped = line.strip()
        if not stripped or stripped.startswith("--"):
            continue
        buf += line
        if sqlite3.complete_statement(buf):
            stmt = buf.strip()
            if stmt:
                out.append(stmt)
            buf = ""
    tail = buf.strip()
    if tail:
        out.append(tail)
    return out


def sqlite_connect(path: Path) -> sqlite3.Connection:
    """One connection for the local database: WAL mode (safeguard 4), a busy
    timeout so three workers writing at once wait instead of failing, foreign
    keys enforced, full sync so a crash cannot lose a committed migration."""
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path))
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=FULL")
    conn.execute("PRAGMA busy_timeout=30000")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def _sha256(path: Path) -> str | None:
    if not path.exists():
        return None
    return hashlib.sha256(path.read_bytes()).hexdigest()


def backup_sqlite(db_path: Path, backup_root: Path | None = None) -> Path:
    """Copy the local database file (+ WAL + shared-memory file) and record a
    SHA-256 manifest. The WAL is checkpointed first so the copy holds every
    committed page. Returns the backup folder."""
    root = backup_root or (db_path.parent / ".backups")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    dest = root / stamp
    dest.mkdir(parents=True)
    if db_path.exists():
        conn = sqlite3.connect(str(db_path))
        try:
            conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        finally:
            conn.close()
    manifest: dict[str, object] = {"backend": "sqlite", "source_db": str(db_path),
                                   "created_at_utc": stamp, "files": {}}
    for suffix in ("", "-wal", "-shm"):
        src = Path(str(db_path) + suffix)
        if src.exists():
            shutil.copy2(src, dest / src.name)
            manifest["files"][src.name] = {"bytes": src.stat().st_size, "sha256": _sha256(src)}
    (dest / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return dest


def restore_sqlite(db_path: Path, backup_dir: Path) -> None:
    """Put a backup back exactly as it was: verify its manifest first, then
    replace the database file (+ WAL + shared-memory file). The backup may
    have been taken from a differently-named file, so manifest entries are
    matched by their suffix ('' / '-wal' / '-shm'), not by name."""
    manifest = json.loads((Path(backup_dir) / "manifest.json").read_text(encoding="utf-8"))
    src_base = Path(str(manifest.get("source_db", db_path))).name
    for suffix in ("", "-wal", "-shm"):
        src = Path(backup_dir) / (src_base + suffix)
        info = manifest["files"].get(src_base + suffix)
        dest = Path(str(db_path) + suffix)
        if info is None:
            if dest.exists():
                dest.unlink()
            continue
        if _sha256(src) != info["sha256"]:
            raise MigrationError(f"backup {backup_dir} is corrupt: {src.name} does not match its manifest; not restoring")
        shutil.copy2(src, dest)


def run_pre_migration_backup() -> None:
    """MySQL hook for the same backup-first rule: a server database cannot be
    file-copied, so the operator wires their snapshot command here (for
    example a tools/db/backup.py run). Only runs when the operator sets
    OTSI_VIE_PRE_MIGRATION_BACKUP; a failing command stops the migration."""
    cmd = os.environ.get("OTSI_VIE_PRE_MIGRATION_BACKUP")
    if not cmd:
        return
    import shlex

    proc = subprocess.run(shlex.split(cmd), capture_output=True, text=True)
    if proc.returncode != 0:
        raise MigrationError(
            "pre-migration backup command failed, so the migration did not run: "
            f"{cmd} ({(proc.stderr or proc.stdout).strip()[:400]})"
        )


def bootstrap_sqlite(dsn: str, applied_by: str = "migrate.py") -> list[str]:
    """Create a fresh local database from database/sqlite-bootstrap.sql and
    record every migration version as applied (with the SQLite file's own
    name and SHA-256, so plan() can verify them later). Refuses when the
    file already holds an applied schema — that database upgrades with up,
    it is never re-bootstrapped."""
    path = sqlite_path(dsn)
    if not SQLITE_BOOTSTRAP_FILE.exists():
        raise MigrationError(f"SQLite bootstrap file is missing: {SQLITE_BOOTSTRAP_FILE}")
    if path.exists() and path.stat().st_size > 0:
        probe = sqlite3.connect(str(path))
        try:
            rows = probe.execute(
                "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='schema_migrations'"
            ).fetchone()[0]
            if rows:
                applied_count = probe.execute("SELECT COUNT(*) FROM schema_migrations").fetchone()[0]
                if applied_count:
                    raise MigrationError(
                        f"{path} already has {applied_count} applied migrations; "
                        "use 'up' to upgrade it, never bootstrap over it"
                    )
        finally:
            probe.close()
    migrations = discover_sqlite()
    conn = sqlite_connect(path)
    try:
        conn.execute("BEGIN IMMEDIATE")
        # executescript() would COMMIT first and break the transaction, so
        # the bootstrap file is run statement by statement instead.
        for stmt in split_sqlite_statements(SQLITE_BOOTSTRAP_FILE.read_text(encoding="utf-8")):
            conn.execute(stmt)
        conn.execute(SQLITE_BOOTSTRAP_TABLE)
        now_ms = int(time.time() * 1000)
        for m in migrations:
            conn.execute(
                "INSERT INTO schema_migrations (version, name, sha256, applied_by, applied_at, duration_ms)"
                " VALUES (?,?,?,?,?,0)",
                (m.version, m.name, m.sha256, applied_by, now_ms),
            )
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
    return [m.name for m in migrations]


def status_sqlite(dsn: str) -> list[tuple[str, str, str]]:
    path = sqlite_path(dsn)
    if not path.exists() or path.stat().st_size == 0:
        return [(m.version, m.name, "pending") for m in discover_sqlite()]
    conn = sqlite_connect(path)
    try:
        conn.execute(SQLITE_BOOTSTRAP_TABLE)
        done = {v: (n, h) for v, n, h in conn.execute(
            "SELECT version, name, sha256 FROM schema_migrations ORDER BY version").fetchall()}
    finally:
        conn.close()
    return [(m.version, m.name, "applied" if m.version in done else "pending")
            for m in discover_sqlite()]


def up_sqlite(dsn: str, migrations: list[Migration] | None = None, applied_by: str = "migrate.py") -> list[str]:
    path = sqlite_path(dsn)
    migrations = discover_sqlite() if migrations is None else migrations
    if not path.exists() or path.stat().st_size == 0:
        return bootstrap_sqlite(dsn, applied_by)
    conn = sqlite_connect(path)
    try:
        conn.execute(SQLITE_BOOTSTRAP_TABLE)
        # plan() reads through a cursor; a sqlite3 cursor supports the same
        # SELECT the MySQL path uses, so the shared checks apply unchanged.
        pending = plan(conn.cursor(), migrations)
    finally:
        conn.close()
    if not pending:
        return []
    # Backup FIRST, before any migration touches the file (safeguard 6).
    backup_dir = backup_sqlite(path)
    conn = sqlite_connect(path)
    ran: list[str] = []
    try:
        # Foreign keys stay OFF inside the transaction: several migrations
        # rebuild a table (SQLite cannot ADD a constraint to an existing
        # table), and a rebuild renames tables other tables point at.
        # Integrity is re-checked after the commit (foreign_key_check below).
        # Legacy rename is ON for the same reason: a view naming the rebuilt
        # table would otherwise fail the rename while the table is dropped.
        conn.execute("PRAGMA foreign_keys=OFF")
        conn.execute("PRAGMA legacy_alter_table=ON")
        conn.execute("BEGIN IMMEDIATE")
        try:
            for m in pending:
                t0 = time.monotonic()
                for k, stmt in enumerate(split_sqlite_statements(m.sql), 1):
                    try:
                        conn.execute(stmt)
                    except sqlite3.Error as e:
                        raise MigrationError(
                            f"Migration {m.name} failed at statement {k}: {e}. "
                            "The database was restored from the backup taken before this run; nothing changed."
                        ) from None
                conn.execute(
                    "INSERT INTO schema_migrations (version, name, sha256, applied_by, applied_at, duration_ms)"
                    " VALUES (?,?,?,?,?,?)",
                    (m.version, m.name, m.sha256, applied_by,
                     int(time.time() * 1000), int((time.monotonic() - t0) * 1000)),
                )
                ran.append(m.name)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        # Now prove the migrated database is whole before reporting success.
        conn.execute("PRAGMA legacy_alter_table=OFF")
        conn.execute("PRAGMA foreign_keys=ON")
        violations = conn.execute("PRAGMA foreign_key_check").fetchall()
        if violations:
            raise MigrationError(
                f"Migration left {len(violations)} foreign-key violations "
                f"(for example {violations[0]}). The database was restored from the backup taken before this run; nothing changed."
            )
        bad = conn.execute("PRAGMA integrity_check").fetchone()[0]
        if bad != "ok":
            raise MigrationError(
                f"Migration left the database failing its integrity check: {bad}. "
                "The database was restored from the backup taken before this run; nothing changed."
            )
    except MigrationError:
        conn.close()
        restore_sqlite(path, backup_dir)
        raise
    except Exception as e:
        conn.close()
        restore_sqlite(path, backup_dir)
        raise MigrationError(
            f"Migration failed ({e}). The database was restored from the backup taken before this run; nothing changed."
        ) from None
    conn.close()
    return ran


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("command", choices=["status", "up", "bootstrap"])
    ap.add_argument("--dsn", default=os.environ.get("OTSI_VIE_DB_DSN"))
    a = ap.parse_args()
    if not a.dsn:
        ap.error("give --dsn or set OTSI_VIE_DB_DSN")
    try:
        if a.command == "status":
            for row in status(a.dsn):
                print("  ".join(row))
        elif a.command == "bootstrap":
            if backend_of(a.dsn) != "sqlite":
                ap.error("bootstrap is only for a sqlite:// DSN")
            ran = bootstrap_sqlite(a.dsn)
            print(f"bootstrapped from sqlite-bootstrap.sql; recorded {len(ran)} migrations as applied")
        else:
            ran = up(a.dsn)
            print("applied:", ", ".join(ran) if ran else "nothing pending")
    except MigrationError as e:
        print(f"MIGRATION STOPPED: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
